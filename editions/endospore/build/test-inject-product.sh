#!/usr/bin/env bash
# test-inject-product.sh [--mutate] [<inject-product.sh>] -- NWP-20261027-18.
#
# WHY THIS IS COMMITTED. inject-product.sh runs on every Endospore build (build-device.sh) after adevtool
# regenerates vendor/google_devices/<dev>/{<dev>.mk,BoardConfig.mk}, yet no suite executed it, and its three
# presence greps counted ANY mention as "already wired": a commented-out inherit line skipped the inherit block
# and, through inherit-product-if-exists, built an image WITHOUT the Endospore product fragment, silently; a
# `BUILD_BROKEN_ELF_PREBUILT_PRODUCT_COPY_FILES := false` skipped the flag and failed the bundled-app JNI libs.
#
# These cases run the script on SYNTHETIC trees: apply, device argument, idempotent re-run, both refusals and the
# three "a mention is not a directive" cases. They cannot show that the real adevtool output looks like the
# fixture -- that is the build host's. Bash only (build-device.sh runs it as `bash`, never on the device).
# CI runs it plain and with --mutate.
#
#   bash test-inject-product.sh              # the script next to this suite
#   bash test-inject-product.sh --mutate     # ... plus mutants that must each CONVICT the suite
#   bash test-inject-product.sh <script>     # that copy (e.g. origin/main's, to see cases e-g fail there)
set -uo pipefail

MUTATE=no; SUT=""
for a in "$@"; do case "$a" in --mutate) MUTATE=yes ;; *) SUT="$a" ;; esac; done
HERE="$(cd "$(dirname "$0")" && pwd)"
[ -n "$SUT" ] || SUT="$HERE/inject-product.sh"

command -v python3 >/dev/null || { echo "python3 is required"; exit 2; }

W=$(mktemp -d) || exit 2
trap 'rm -rf "$W"' EXIT

PASS=0; FAIL=0
ok(){ PASS=$((PASS+1)); printf '  ok    %s\n' "$1"; }
no(){ FAIL=$((FAIL+1)); printf '  FAIL  %s\n' "$1"; }
# ⚠ Every match reads its input to the end: `grep -c ... >/dev/null`, never `grep -q`.
count(){ grep -cxF -- "$2" "$1"; }
same(){ cmp -s "$1" "$2"; }
# check <label> <command...>: one case line.
check(){ local l="$1"; shift; if "$@"; then ok "$l"; else no "$l"; fi; }

MARK1='# --- endospore: inherit edition product fragment (inject-product.sh) ---'
LINE1='$(call inherit-product-if-exists, vendor/endospore/endospore.mk)'
MARK2='# --- endospore: confined SELinux domain (system-side private policy) ---'
LINE2='SYSTEM_EXT_PRIVATE_SEPOLICY_DIRS += vendor/endospore/sepolicy'
MARK3='# --- endospore: allow legacy ELF .so (bundled-app JNI) in PRODUCT_COPY_FILES ---'
LINE3='BUILD_BROKEN_ELF_PREBUILT_PRODUCT_COPY_FILES := true'
GEN='# Generated by adevtool; do not edit'

# mktree <dev> <mk body> <BoardConfig.mk body>: a fixture tree under $W; echoes its path.
mktree(){
  local t d; t=$(mktemp -d -p "$W") || exit 2
  d="$t/vendor/google_devices/$1"; mkdir -p "$d"
  printf '%s\n' "$2" > "$d/$1.mk"
  printf '%s\n' "$3" > "$d/BoardConfig.mk"
  echo "$t"
}
MK_BODY="$GEN
\$(call inherit-product, vendor/google/other/other.mk)"
BC_BODY="$GEN
BOARD_VENDOR_SEPOLICY_DIRS += device/google/other/sepolicy"
# run <sut> <tree> [dev]: the script's exit code; its output is left in <tree>.out.
run(){ bash "$1" "$2" ${3:+"$3"} > "$2.out" 2>&1; echo $?; }
# line_of <file> <text>: the number of the first line that is exactly <text>.
line_of(){ grep -nxF -- "$2" "$1" | head -n1 | cut -d: -f1; }
# appended_once <file> <mark> <line>: both appear exactly once, the line directly after its mark.
appended_once(){
  [ "$(count "$1" "$2")" = 1 ] && [ "$(count "$1" "$3")" = 1 ] || return 1
  [ "$(( $(line_of "$1" "$2") + 1 ))" = "$(line_of "$1" "$3")" ]
}
# prefix_kept <orig> <new>: <new> starts with every byte of <orig>.
prefix_kept(){ cmp -s "$1" <(head -c "$(wc -c < "$1")" "$2"); }
before(){ [ -n "$2" ] && [ -n "$3" ] && [ "$2" -lt "$3" ]; }
all_ok(){ local c; for c in "$@"; do [ "$c" = 0 ] || return 1; done; }

suite(){
  local S="$1" T T2 rc MK BC TD
  # (a) pristine lynx tree, no device argument
  T=$(mktree lynx "$MK_BODY" "$BC_BODY"); MK="$T/vendor/google_devices/lynx/lynx.mk"; BC="$T/vendor/google_devices/lynx/BoardConfig.mk"
  cp "$MK" "$W/a.mk"; cp "$BC" "$W/a.bc"
  rc=$(run "$S" "$T")
  check "a: pristine lynx tree exits 0" test "$rc" = 0
  check "a: inherit block appended exactly once" appended_once "$MK" "$MARK1" "$LINE1"
  check "a: sepolicy block appended exactly once" appended_once "$BC" "$MARK2" "$LINE2"
  check "a: ELF flag block appended exactly once" appended_once "$BC" "$MARK3" "$LINE3"
  check "a: blocks in order (sepolicy before ELF flag)" before x "$(line_of "$BC" "$MARK2")" "$(line_of "$BC" "$MARK3")"
  check "a: rest of lynx.mk byte-identical" prefix_kept "$W/a.mk" "$MK"
  check "a: rest of BoardConfig.mk byte-identical" prefix_kept "$W/a.bc" "$BC"
  cp "$MK" "$W/a1.mk"; cp "$BC" "$W/a1.bc"

  # (b) the device argument edits that device only
  T2=$(mktree lynx "$MK_BODY" "$BC_BODY"); TD="$T2/vendor/google_devices/tegu"; mkdir -p "$TD"
  printf '%s\n' "$GEN" > "$TD/tegu.mk"; printf '%s\n%s\n' "$GEN" 'BOARD_X := 1' > "$TD/BoardConfig.mk"
  cp "$T2/vendor/google_devices/lynx/lynx.mk" "$W/b.mk"; cp "$T2/vendor/google_devices/lynx/BoardConfig.mk" "$W/b.bc"
  rc=$(run "$S" "$T2" tegu)
  check "b: tegu exits 0" test "$rc" = 0
  check "b: tegu inherit block appended" appended_once "$TD/tegu.mk" "$MARK1" "$LINE1"
  check "b: tegu sepolicy block appended" appended_once "$TD/BoardConfig.mk" "$MARK2" "$LINE2"
  check "b: tegu ELF flag block appended" appended_once "$TD/BoardConfig.mk" "$MARK3" "$LINE3"
  check "b: lynx.mk beside it byte-identical" same "$W/b.mk" "$T2/vendor/google_devices/lynx/lynx.mk"
  check "b: lynx BoardConfig.mk beside it byte-identical" same "$W/b.bc" "$T2/vendor/google_devices/lynx/BoardConfig.mk"

  # (c) re-run of (a) is a no-op
  rc=$(run "$S" "$T")
  check "c: re-run exits 0" test "$rc" = 0
  check "c: three 'already' lines" test "$(grep -c 'already' "$T.out")" = 3
  check "c: lynx.mk byte-identical" same "$W/a1.mk" "$MK"
  check "c: BoardConfig.mk byte-identical" same "$W/a1.bc" "$BC"

  # (d) a missing file refuses and leaves the other untouched
  T=$(mktree lynx "$MK_BODY" "$BC_BODY"); rm "$T/vendor/google_devices/lynx/lynx.mk"
  cp "$T/vendor/google_devices/lynx/BoardConfig.mk" "$W/d.bc"
  rc=$(run "$S" "$T")
  check "d: missing lynx.mk exits 1" test "$rc" = 1
  check "d: BoardConfig.mk byte-identical" same "$W/d.bc" "$T/vendor/google_devices/lynx/BoardConfig.mk"
  T=$(mktree lynx "$MK_BODY" "$BC_BODY"); rm "$T/vendor/google_devices/lynx/BoardConfig.mk"
  cp "$T/vendor/google_devices/lynx/lynx.mk" "$W/d.mk"
  rc=$(run "$S" "$T")
  check "d: missing BoardConfig.mk exits 1" test "$rc" = 1
  check "d: lynx.mk byte-identical" same "$W/d.mk" "$T/vendor/google_devices/lynx/lynx.mk"

  # (e) a commented-out inherit is not wired
  T=$(mktree lynx "$MK_BODY
# $LINE1" "$BC_BODY"); MK="$T/vendor/google_devices/lynx/lynx.mk"
  rc=$(run "$S" "$T")
  check "e: commented inherit exits 0" test "$rc" = 0
  check "e: live inherit block appended after the comment" appended_once "$MK" "$MARK1" "$LINE1"
  T=$(mktree lynx "$MK_BODY
   #$LINE1" "$BC_BODY"); MK="$T/vendor/google_devices/lynx/lynx.mk"
  rc=$(run "$S" "$T")
  check "e: an indented comment is a comment too" appended_once "$MK" "$MARK1" "$LINE1"

  # (f) ':= false' is not wired; the true assignment is appended after it
  T=$(mktree lynx "$MK_BODY" "$BC_BODY
BUILD_BROKEN_ELF_PREBUILT_PRODUCT_COPY_FILES := false"); BC="$T/vendor/google_devices/lynx/BoardConfig.mk"
  rc=$(run "$S" "$T")
  check "f: ':= false' exits 0" test "$rc" = 0
  check "f: flag block appended once" appended_once "$BC" "$MARK3" "$LINE3"
  check "f: the true assignment comes after the false one" before x "$(line_of "$BC" 'BUILD_BROKEN_ELF_PREBUILT_PRODUCT_COPY_FILES := false')" "$(line_of "$BC" "$LINE3")"

  # (g) the sepolicy path only in a comment is not wired
  T=$(mktree lynx "$MK_BODY" "$BC_BODY
# see vendor/endospore/sepolicy"); BC="$T/vendor/google_devices/lynx/BoardConfig.mk"
  rc=$(run "$S" "$T")
  check "g: comment-only mention exits 0" test "$rc" = 0
  check "g: sepolicy block appended once" appended_once "$BC" "$MARK2" "$LINE2"
}

echo "== inject-product.sh: $SUT =="
suite "$SUT"
echo "pass=$PASS fail=$FAIL"
[ "$FAIL" = 0 ] || exit 1

if [ "$MUTATE" = yes ]; then
  echo "== mutants =="
  MFAIL=0
  # mutant <name> <regex> <replacement>: a copy of the script with the first match replaced. A mutant that
  # does not change the text is an error; a mutant must turn the suite red.
  mutant(){
    local n="$1" f="$W/mut-$1.sh" out sp=$PASS sf=$FAIL
    if ! python3 -I - "$SUT" "$f" "$2" "$3" <<'PY'
import re, sys
src, dst, pat, rep = sys.argv[1:5]
s = open(src, encoding='utf-8').read()
t, n = re.subn(pat, lambda m: rep, s, count=1, flags=re.M)
if n != 1 or t == s: sys.exit(1)
open(dst, 'w', encoding='utf-8', newline='\n').write(t)
PY
    then echo "  ERROR $n: mutant did not change the text"; MFAIL=$((MFAIL+1)); return; fi
    out=$(suite "$f" 2>&1)
    PASS=$sp; FAIL=$sf
    if printf '%s\n' "$out" | grep -c '^  FAIL' >/dev/null && [ -n "$(printf '%s\n' "$out" | grep '^  FAIL')" ]; then
      echo "  convicted $n: $(printf '%s\n' "$out" | grep '^  FAIL' | head -n1 | sed 's/^  FAIL  //')"
    else
      echo "  SURVIVED  $n"; MFAIL=$((MFAIL+1))
    fi
  }
  mutant I1-inherit-check-any-mention "grep -qE '[^']*vendor/endospore/endospore[^']*' \"\\\$MK\"" "grep -qF 'vendor/endospore/endospore.mk' \"\$MK\""
  mutant I2-elf-check-bare-name "grep -qE '\\^[^']*BUILD_BROKEN_ELF[^']*' \"\\\$BC\"" "grep -qF 'BUILD_BROKEN_ELF_PREBUILT_PRODUCT_COPY_FILES' \"\$BC\""
  mutant I3-sepolicy-check-dropped "if grep -qE '[^']*vendor/endospore/sepolicy' \"\\\$BC\"; then" "if false; then"
  mutant I4-boardconfig-existence-check-removed '^\[ -f "\$BC" \].*$' ":"
  [ "$MFAIL" = 0 ] || { echo "$MFAIL mutant(s) not convicted"; exit 1; }
fi
exit 0
