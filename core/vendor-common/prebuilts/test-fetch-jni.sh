#!/usr/bin/env bash
# test-fetch-jni.sh -- NWP-20261103-13. fetch-default-apps.sh's JNI section fails loudly and leaves no fragment.
#
# WHY THIS EXISTS. The section ran `unzip ... || true` and skipped a missing APK, so a build host without unzip, a
# corrupt APK or an APK with no arm64 libs wrote a default-apps-jni.mk that named nothing for that app and the script
# exited 0. Both editions -include the fragment silently and build-device.sh stops only on a non-zero exit, so the
# release shipped OrganicMaps/NewPipe/AntennaPod crashing at launch (compressed libs, extractNativeLibs=true, never
# unpacked). Now each of those is FATAL, and the fragment is moved into place only after every app passed.
#
#   j1 two apps with arm64 libs: exit 0, one PRODUCT_COPY_FILES line per .so, today's fragment and output bytes;
#   j2 an app with only armeabi-v7a: exit 1 naming it, no fragment (a planted earlier one is gone too);
#   j3 no unzip on PATH: exit 1 with the unzip FATAL before any app is processed, no fragment;
#   j4 a named APK absent: exit 1 naming it, no fragment;
#   j5 JNI_APPS=" ": exit 0 with no unzip (test-prebuilt-pins.sh case (d) runs the script that way);
#   j6 (a) an APK that is not a zip, (b) a zip with one good lib and one with a bad CRC (unzip extracts the good one
#      and exits 2, so only the exit-status check can catch it): exit 1 naming the app, no fragment.
#
# --mutate re-runs the cases against broken copies of the script, each of which must FAIL its named case:
# J1 the unzip check deleted (j3), J2 the n=0 check deleted (j2), J3 the unzip exit-status check deleted, i.e. the old
# `|| true` (j6), J4 the missing-APK arm back to `continue` (j4), J5 the fragment written in place (j2), J6 the unzip
# check made unconditional (j5). A mutant that does not apply is a failure.
#
# Needs bash and python3 (the APK builder and the `unzip` shim on the cases' PATH, so the host needs no unzip). It is
# bash-only because the script under test is `#!/bin/bash`. FETCH_UNDER_TEST=<file> runs the cases against another
# copy of the script (e.g. origin/main's, to see j2/j3/j4/j6 fail there).
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
FETCH="${FETCH_UNDER_TEST:-$HERE/fetch-default-apps.sh}"

PY="$(command -v python3 || true)"
if [ -z "$PY" ]; then
  echo "FAIL: python3 is required (the unzip shim and the APK builder)"
  exit 1
fi
pyver="$("$PY" --version 2>&1)"
echo "python3: $pyver"

W=$(mktemp -d) || exit 2
trap 'rm -rf "$W"' EXIT

BASH_BIN="$(command -v bash)"
TOOLS="$W/tools"
TOOLS_NOUNZIP="$W/tools-nounzip"
mkdir -p "$TOOLS" "$TOOLS_NOUNZIP"
for t in bash sha256sum cut dirname basename rm mkdir mv sed; do
  p="$(command -v "$t" || true)"
  [ -n "$p" ] || { echo "FAIL: $t is required"; exit 2; }
  ln -s "$p" "$TOOLS/$t"
  ln -s "$p" "$TOOLS_NOUNZIP/$t"
done

# unzip -j -o ZIP GLOB -d DIR: Info-ZIP's exit codes for the three outcomes the script distinguishes.
cat > "$TOOLS/unzip" <<EOF
#!$PY -I
import fnmatch, os, sys, zipfile
a = sys.argv[1:]
if len(a) != 6 or a[:2] != ["-j", "-o"] or a[4] != "-d":
    sys.exit(10)
zpath, glob, dest = a[2], a[3], a[5]
try:
    z = zipfile.ZipFile(zpath)
except (zipfile.BadZipFile, OSError):
    sys.exit(9)
names = [n for n in z.namelist() if fnmatch.fnmatch(n, glob)]
if not names:
    sys.exit(11)
os.makedirs(dest, exist_ok=True)
rc = 0
for n in names:
    try:
        data = z.read(n)
    except zipfile.BadZipFile as e:
        print(e, file=sys.stderr)
        rc = 2
        continue
    with open(os.path.join(dest, os.path.basename(n)), "wb") as f:
        f.write(data)
sys.exit(rc)
EOF
chmod +x "$TOOLS/unzip"

# mkapk OUT MEMBER...: a stored zip, each member's payload is its own name.
mkapk() {
  "$PY" -I -c '
import sys, zipfile
with zipfile.ZipFile(sys.argv[1], "w", zipfile.ZIP_STORED) as z:
    for m in sys.argv[2:]:
        z.writestr(m, m)
' "$@"
}

# mkapk_badcrc OUT: libgood.so intact, libbad.so with a stored byte flipped after its CRC was written.
mkapk_badcrc() {
  mkapk "$1" lib/arm64-v8a/libgood.so lib/arm64-v8a/libbad.so || return 1
  "$PY" -I -c '
import sys
p = sys.argv[1]
b = bytearray(open(p, "rb").read())
name = b"lib/arm64-v8a/libbad.so"
i = b.find(name, b.find(name) + 1)  # the first hit is the local header name, the second the stored payload
if i < 0:
    sys.exit(2)
b[i] ^= 1
open(p, "wb").write(b)
' "$1"
}

HEADER='# AUTO-GENERATED by fetch-default-apps.sh -- do not edit, do not commit (.gitignored).
# Per-app arm64 JNI .so extracted from the F-Droid APKs (compressed, extractNativeLibs=true) and
# copied into each app'"'"'s /product lib dir so the loader resolves them. Regenerated on every fetch.'

# mkcase SCRIPT: sets T (a scratch tree holding a copy of SCRIPT under vendor/x/prebuilts, comments-only manifest).
mkcase() {
  T="$(mktemp -d -p "$W")"
  P="$T/vendor/x/prebuilts"
  mkdir -p "$P"
  cp "$1" "$P/fetch-default-apps.sh"
  printf '# no rows: the fetch loop does nothing\n' > "$P/default-apps.manifest"
}

# run_fetch TOOLS APPS: sets out and rc.
run_fetch() {
  out="$(cd "$T" && PATH="$1" JNI_APPS="$2" "$BASH_BIN" vendor/x/prebuilts/fetch-default-apps.sh 2>&1)"
  rc=$?
}

plant_stale() { printf 'PRODUCT_COPY_FILES += stale\n' > "$P/default-apps-jni.mk"; }

fail() { echo "FAIL $1: $2"; return 1; }

no_frag() {
  [ ! -e "$P/default-apps-jni.mk" ] || { fail "$1" "a fragment is left behind"; return 1; }
  [ ! -e "$P/default-apps-jni.mk.tmp" ] || { fail "$1" "a .tmp fragment is left behind"; return 1; }
}

has() { [[ $out == *"$2"* ]] || fail "$1" "output lacks: $2"; }

case_j1() {
  mkcase "$1"
  mkapk "$P/AppA.apk" lib/arm64-v8a/libfoo.so lib/armeabi-v7a/libbar.so
  mkapk "$P/AppB.apk" lib/arm64-v8a/libbaz.so
  run_fetch "$TOOLS" "AppA AppB"
  [ "$rc" -eq 0 ] || { fail j1 "exit $rc: $out"; return 1; }
  local want got
  want="$HEADER
PRODUCT_COPY_FILES += vendor/x/prebuilts/jni/AppA/arm64/libfoo.so:\$(TARGET_COPY_OUT_PRODUCT)/app/AppA/lib/arm64/libfoo.so
PRODUCT_COPY_FILES += vendor/x/prebuilts/jni/AppB/arm64/libbaz.so:\$(TARGET_COPY_OUT_PRODUCT)/app/AppB/lib/arm64/libbaz.so"
  got="$(cat "$P/default-apps-jni.mk")"
  [ "$got" = "$want" ] || { fail j1 "fragment differs: $got"; return 1; }
  has j1 "jni  AppA  (1 arm64 .so)" || return 1
  has j1 "jni  AppB  (1 arm64 .so)" || return 1
  has j1 "wrote $P/default-apps-jni.mk" || return 1
  [ ! -e "$P/default-apps-jni.mk.tmp" ] || { fail j1 ".tmp left behind"; return 1; }
  echo "ok j1 two apps with arm64 libs: fragment and output as before"
}

case_j2() {
  mkcase "$1"
  plant_stale
  mkapk "$P/AppA.apk" lib/arm64-v8a/libfoo.so
  mkapk "$P/AppB.apk" lib/armeabi-v7a/libbar.so
  run_fetch "$TOOLS" "AppA AppB"
  [ "$rc" -eq 1 ] || { fail j2 "exit $rc, want 1: $out"; return 1; }
  has j2 "FATAL no arm64-v8a .so extracted from AppB.apk" || return 1
  no_frag j2 || return 1
  echo "ok j2 an app with no arm64 lib fails, no fragment"
}

case_j3() {
  mkcase "$1"
  plant_stale
  mkapk "$P/AppA.apk" lib/arm64-v8a/libfoo.so
  mkapk "$P/AppB.apk" lib/arm64-v8a/libbaz.so
  run_fetch "$TOOLS_NOUNZIP" "AppA AppB"
  [ "$rc" -eq 1 ] || { fail j3 "exit $rc, want 1: $out"; return 1; }
  has j3 "FATAL unzip is required to extract the JNI libs of: AppA AppB" || return 1
  [[ $out != *"jni  "* ]] || { fail j3 "an app was processed before the check"; return 1; }
  no_frag j3 || return 1
  echo "ok j3 no unzip fails before any app is processed"
}

case_j4() {
  mkcase "$1"
  mkapk "$P/AppA.apk" lib/arm64-v8a/libfoo.so
  run_fetch "$TOOLS" "AppA AppB"
  [ "$rc" -eq 1 ] || { fail j4 "exit $rc, want 1: $out"; return 1; }
  has j4 "FATAL AppB.apk is missing but JNI_APPS names it" || return 1
  no_frag j4 || return 1
  echo "ok j4 a missing JNI APK fails, no fragment"
}

case_j5() {
  mkcase "$1"
  run_fetch "$TOOLS_NOUNZIP" " "
  [ "$rc" -eq 0 ] || { fail j5 "exit $rc: $out"; return 1; }
  [ "$(cat "$P/default-apps-jni.mk")" = "$HEADER" ] || { fail j5 "fragment is not the bare header"; return 1; }
  has j5 "wrote " || return 1
  echo "ok j5 empty JNI_APPS needs no unzip"
}

case_j6() {
  local half
  for half in a b; do
    mkcase "$1"
    if [ "$half" = a ]; then
      printf 'not a zip\n' > "$P/AppA.apk"
    else
      mkapk_badcrc "$P/AppA.apk" || { fail j6 "could not build the bad-CRC apk"; return 1; }
    fi
    mkapk "$P/AppB.apk" lib/arm64-v8a/libbaz.so
    run_fetch "$TOOLS" "AppA AppB"
    [ "$rc" -eq 1 ] || { fail "j6$half" "exit $rc, want 1: $out"; return 1; }
    has "j6$half" "FATAL no arm64-v8a .so extracted from AppA.apk" || return 1
    no_frag "j6$half" || return 1
  done
  echo "ok j6 a corrupt APK (not a zip; bad CRC) fails, no fragment"
}

run_all() {
  local c rc_all=0
  for c in j1 j2 j3 j4 j5 j6; do
    "case_$c" "$1" || rc_all=1
  done
  return $rc_all
}

if [ "${1:-}" != "--mutate" ]; then
  if run_all "$FETCH"; then echo "PASS: fetch-default-apps.sh JNI extraction fails loud"; exit 0; fi
  echo "FAIL: see above"
  exit 1
fi

# --mutate
run_all "$FETCH" >/dev/null || { echo "FAIL: the unmutated script does not pass the cases"; exit 1; }
bad=0
# mutant NAME CASE SED-EXPR
mutant() {
  local m="$1" c="$2" expr="$3" copy
  copy="$(mktemp -p "$W")"
  sed -E "$expr" "$FETCH" > "$copy"
  if cmp -s "$FETCH" "$copy"; then echo "FAIL: mutant $m did not apply"; bad=1; return; fi
  if "case_$c" "$copy" >/dev/null 2>&1; then
    echo "SURVIVED $m (case $c still passes)"; bad=1
  else
    echo "killed $m (case $c)"
  fi
}
mutant J1 j3 '/command -v unzip/d'
mutant J2 j2 '/\[ "\$n" -gt 0 \] \|\| jni_fatal/d'
mutant J3 j6 '/\[ "\$urc" -eq 0 \] \|\| \[ "\$urc" -eq 11 \] \|\| jni_fatal/d'
mutant J4 j4 's/(\[ -f "\$apk" \] \|\| )jni_fatal .*/\1continue/'
mutant J5 j2 's/> "\$FRAG\.tmp"$/> "$FRAG"/'
mutant J6 j5 's/^\[ -z "\$\{JNI_APPS\/\/\[\[:space:\]\]\/\}" \] \|\| //'
if [ "$bad" -eq 0 ]; then echo "PASS: all six mutants killed"; exit 0; fi
exit 1
