#!/bin/bash
# Fetch the Nowhere default apps (DIA-20260617-06) from F-Droid at the versions pinned in
# default-apps.manifest. The APKs are gitignored (not committed; ~277 MB; WireGuard is the one committed exception),
# so run this ONCE on a fresh tree before `m systemimage` -- the Android.bp android_app_import modules expect
# prebuilts/<Name>.apk. Rows marked `manual` are never fetched, only verified (see below).
# Idempotent: an APK already present with the pinned SHA256 is left alone. Verifies SHA256 after download
# (a mismatch -> hard fail, so a tampered/rotated mirror can't slip in a different binary).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
MANIFEST="$HERE/default-apps.manifest"
[ -f "$MANIFEST" ] || { echo "no manifest at $MANIFEST" >&2; exit 1; }

sha_of() { sha256sum "$1" | cut -d' ' -f1; }

# A row marked `manual` (5th column; NWP-20261011-22) is not on F-Droid at its pin -- WireGuard is committed in-repo
# and copied in by stage-vendor.sh, AuroraServices is placed by hand. Never build an F-Droid URL for one: when it
# is absent or its sha differs, fail and print the manifest comment above its row, which names its source. The
# file is left in place on a mismatch (it was put there by hand or by the stage, not by this script).
note=""
while IFS= read -r line; do
  read -r name pkg vc sha src _rest <<< "$line" || true
  case "${name:-}" in
    \#*) note="$note${note:+$'\n'}$line"; continue;;
    "") note=""; continue;;
  esac
  out="$HERE/$name.apk"
  if [ -f "$out" ] && [ "$(sha_of "$out")" = "$sha" ]; then
    echo "ok   $name (cached, sha ok)"
    note=""
    continue
  fi
  if [ "${src:-}" = "manual" ]; then
    if [ -f "$out" ]; then
      echo "SHA256 MISMATCH for manual prebuilt $name: got $(sha_of "$out"), want $sha (left in place)" >&2
    else
      echo "MISSING manual prebuilt $name.apk ($pkg vc $vc, sha $sha) in $HERE" >&2
    fi
    echo "  it is not on F-Droid, so this script does not fetch it. Its source, from $MANIFEST:" >&2
    printf '%s\n' "${note:-  (no comment above its row)}" | sed 's/^/    /' >&2
    exit 1
  fi
  note=""
  url="https://f-droid.org/repo/${pkg}_${vc}.apk"
  echo "get  $name  <-  $url"
  curl -fsSL --retry 3 -o "$out" "$url"
  got="$(sha_of "$out")"
  if [ "$got" != "$sha" ]; then
    echo "SHA256 MISMATCH for $name: got $got, want $sha" >&2
    rm -f "$out"
    exit 1
  fi
  echo "ok   $name (downloaded, sha ok)"
done < "$MANIFEST"

echo "all default apps present + verified in $HERE"

# --- JNI libs (DIA-20260618-01) -------------------------------------------------------------------
# F-Droid ships these apps with compressed native libs + extractNativeLibs=true (libs are meant to be
# unpacked at install). A verbatim (preprocessed) system app never unpacks them, so dlopen fails at
# launch (Fennec/OrganicMaps crash; AntennaPod and NewPipe did until their uncompressed-lib pins,
# NWP-20261029-26). Re-zipping the APK to
# uncompress the libs would break its F-Droid v2/v3 signature -- so instead we extract each APK's arm64
# .so here and copy them into the app's /product lib dir (where the loader looks for a system app),
# leaving the APK byte-identical. Emit a PRODUCT_COPY_FILES fragment that diaspore.mk -includes.
# FP3 runs these apps 64-bit, so only arm64-v8a libs are needed (dir name on device is "arm64").
# Every failure below is FATAL (NWP-20261103-13): both editions -include the fragment silently and build-device.sh
# stops only on a non-zero exit, so a missing unzip, a missing APK or an APK with no arm64 .so would otherwise bake
# an app that crashes at launch. The fragment is built in $FRAG.tmp and moved into place only after every app passed.
# Edition-aware: $HERE is .../vendor/<edition>/prebuilts, so the build-relative copy path is
# vendor/<edition>/prebuilts -- derive it instead of hardcoding diaspore (so endospore reuses this).
VENDOR_REL="vendor/$(basename "$(dirname "$HERE")")/prebuilts"
# Overridable so an edition can narrow the set (e.g. Endospore drops Fennec -> uses Vanadium instead).
JNI_APPS="${JNI_APPS:-OrganicMaps Fennec}"
FRAG="$HERE/default-apps-jni.mk"
jni_fatal() { echo "FATAL $*" >&2; rm -f "$FRAG.tmp"; exit 1; }
rm -f "$FRAG" "$FRAG.tmp"
[ -z "${JNI_APPS//[[:space:]]/}" ] || command -v unzip >/dev/null 2>&1 || jni_fatal "unzip is required to extract the JNI libs of: $JNI_APPS"
{
  echo "# AUTO-GENERATED by fetch-default-apps.sh -- do not edit, do not commit (.gitignored)."
  echo "# Per-app arm64 JNI .so extracted from the F-Droid APKs (compressed, extractNativeLibs=true) and"
  echo "# copied into each app's /product lib dir so the loader resolves them. Regenerated on every fetch."
} > "$FRAG.tmp"
for name in $JNI_APPS; do
  apk="$HERE/$name.apk"
  [ -f "$apk" ] || jni_fatal "$name.apk is missing but JNI_APPS names it"
  dest="$HERE/jni/$name/arm64"
  rm -rf "$HERE/jni/$name"
  mkdir -p "$dest"
  urc=0; unzip -j -o "$apk" 'lib/arm64-v8a/*.so' -d "$dest" >/dev/null 2>&1 || urc=$?
  # 11 = "no matching files": left to the n=0 check below
  [ "$urc" -eq 0 ] || [ "$urc" -eq 11 ] || jni_fatal "no arm64-v8a .so extracted from $name.apk -- baked without them it crashes at launch"
  n=0
  for so in "$dest"/*.so; do
    [ -f "$so" ] || continue
    base="$(basename "$so")"
    echo "PRODUCT_COPY_FILES += $VENDOR_REL/jni/$name/arm64/$base:\$(TARGET_COPY_OUT_PRODUCT)/app/$name/lib/arm64/$base" >> "$FRAG.tmp"
    n=$((n+1))
  done
  [ "$n" -gt 0 ] || jni_fatal "no arm64-v8a .so extracted from $name.apk -- baked without them it crashes at launch"
  echo "jni  $name  ($n arm64 .so)"
done
mv -f "$FRAG.tmp" "$FRAG"
echo "wrote $FRAG"
