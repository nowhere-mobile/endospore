#!/usr/bin/env bash
# run.sh <OtaUpdate.java> <ChooserActivity.java> -- NWP-20261113-22: lift the gate's "Preparing the update…" helpers
# (the afterLogoffPrepWatch field, afterLogoffPreparing and afterLogoffPrepHandOff) out of ChooserActivity.java
# UNCHANGED into PrepGate, compile them with the real OtaUpdate and the recording stubs beside this file, and run
# PrepCases. core/vendor-common/bin/test-ota-update-java.sh is the CI entry point and finds $JAVAC / $JAVA.
#
# Exit codes: 1 = a case failed or the helpers are not in ChooserActivity.java; 3 = it did not compile.
set -euo pipefail
OTA="${1:?usage: run.sh OtaUpdate.java ChooserActivity.java}"
CHO="${2:?usage: run.sh OtaUpdate.java ChooserActivity.java}"
JAVAC="${JAVAC:-javac}"
JAVA="${JAVA:-java}"
here=$(cd "$(dirname "$0")" && pwd)
D=$(mktemp -d)
trap 'rm -rf "$D"' EXIT
lifted=$(awk '
  $0 == "    private android.text.TextWatcher afterLogoffPrepWatch; // UI thread only: non-null while the line and bar are ours" { on = 1 }
  on { print }
  on && $0 == "    private void afterLogoffPrepHandOff() {" { last = 1 }
  last && $0 == "    }" { exit }
' "$CHO")
case "$lifted" in
  *"private void afterLogoffPreparing(boolean on) {"*"private void afterLogoffPrepHandOff() {"*) ;;
  *) echo "FAIL the preparing helpers are not where run.sh lifts them from in $CHO" >&2; exit 1 ;;
esac
mkdir -p "$D/src/com/nowhere/chooser"
cp "$OTA" "$D/src/com/nowhere/chooser/OtaUpdate.java"
cp "$here/PrepCases.java" "$D/src/com/nowhere/chooser/"
{
  printf '%s\n' 'package com.nowhere.chooser;' '' 'import android.view.View;' '' \
    '/** Generated by prep/run.sh: the helpers below are lifted unchanged from ChooserActivity.java. */' \
    'final class PrepGate {' \
    '    final android.widget.TextView result = new android.widget.TextView();' \
    '    final android.widget.ProgressBar progressBar = new android.widget.ProgressBar();' \
    '    boolean sessionLive, loginInProgress, resumeMode;' \
    '    void on() { afterLogoffPreparing(true); }' \
    '    void off() { afterLogoffPreparing(false); }' \
    '    void counts() { result.textWrites = 0; progressBar.writes = 0; }' ''
  printf '%s\n' "$lifted"
  printf '%s\n' '}'
} > "$D/src/com/nowhere/chooser/PrepGate.java"
find "$here/stubs" "$D/src" -name '*.java' > "$D/sources"
"$JAVAC" -encoding UTF-8 -source 8 -target 8 -nowarn -d "$D/out" @"$D/sources" 2>"$D/javac.err" \
  || { cat "$D/javac.err" >&2; exit 3; }
"$JAVA" -Djava.io.tmpdir="$D" -cp "$D/out" com.nowhere.chooser.PrepCases
